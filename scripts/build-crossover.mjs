#!/usr/bin/env node
/* build-crossover.mjs — ck-e13.
   Walk every encyclopedia entry that ships a spec.techniques[] block and
   emit two derived indices:

     content/_index/techniques.js  — { <technique_id>: {
                                        name, layer,
                                        appears_in: [{entry_id, plate, params}] } }
     content/_index/atoms.js       — { <atom_name>:    {
                                        used_by:    [{technique_id, entry_id, plate}] } }

   The shell contract forbids fetch under file://, so the indices ship as
   classic scripts that call Shell.registerCrossover(name, data). Loaded
   from encyclopedia/index.html after manifest.js. The plate view's RELATED
   block reads Shell.crossover.techniques; #/technique/<id> and #/atom/<id>
   augment their existing instance / uses aggregations with these fine-
   grained references.

   Regenerate manually:   node scripts/build-crossover.mjs
   Or on push via CI.

   The script runs the encyclopedia manifest inside a sandbox (same shape
   the verifier uses) — no browser, no fetch. */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import vm from 'vm';

const HERE   = dirname(fileURLToPath(import.meta.url));
const ROOT   = join(HERE, '..');
const ENCYC  = join(ROOT, 'encyclopedia');
const OUT    = join(ENCYC, 'content', '_index');

/* --- load the encyclopedia manifest + every content/<slug>/entry.js in a
   sandbox that exposes only what the entry scripts need: a Shell.registerEntry
   collector and a Shell.registerManifest collector. --------------------- */
function loadManifest() {
  const manifest = { entries: [] };
  const collectedEntries = [];
  const sandbox = {
    Shell: {
      registerManifest(m) { Object.assign(manifest, m); },
      registerEntry(e)   { collectedEntries.push(e); },
      registerCrossover() { /* no-op; we're building it */ }
    },
    window: undefined,
    document: { getElementById: () => null }
  };
  const ctx = vm.createContext(sandbox);

  // Load the tool manifest first — it declares which entries register via
  // content/<slug>/entry.js. The manifest also holds inline entries.
  const manifestPath = join(ENCYC, 'manifest.js');
  vm.runInContext(readFileSync(manifestPath, 'utf8'), ctx, { filename: manifestPath });

  // Walk entries[] — a slug means load content/<slug>/entry.js; an object
  // means the entry is inline.
  for (const item of manifest.entries) {
    if (typeof item === 'string') {
      const p = join(ENCYC, 'content', item, 'entry.js');
      if (existsSync(p)) {
        try {
          vm.runInContext(readFileSync(p, 'utf8'), ctx, { filename: p });
        } catch (err) {
          // Entries that reference outer-scope helpers (ST-06's T etc.) can
          // throw at load time. We swallow; those entries won't appear in
          // the crossover, and the verifier will report them separately.
          console.warn(`⚠ ${item}: ${err.message}`);
        }
      }
    } else if (item && typeof item === 'object') {
      collectedEntries.push(item);
    }
  }
  return collectedEntries;
}

/* --- build the two indices ---------------------------------------------- */
function build(entries) {
  const techniques = {};
  const atoms      = {};

  for (const entry of entries) {
    const specTechniques = entry.spec && entry.spec.techniques;
    if (!Array.isArray(specTechniques)) continue;

    for (const tech of specTechniques) {
      if (!tech.id) continue;
      if (!techniques[tech.id]) {
        techniques[tech.id] = { name: tech.name || tech.id, layer: tech.layer || null, appears_in: [] };
      }
      techniques[tech.id].appears_in.push({
        entry_id: entry.id,
        plate:    entry.index || null,
        // Params can be large — carry a size hint rather than the full object,
        // so the index stays small enough to load as a script at boot. The
        // plate's own entry.js already holds the full params.
        params_keys: tech.params ? Object.keys(tech.params).length : 0
      });

      const atomList = Array.isArray(tech.atoms) ? tech.atoms : [];
      for (const atomName of atomList) {
        if (!atoms[atomName]) atoms[atomName] = { used_by: [] };
        atoms[atomName].used_by.push({
          technique_id: tech.id,
          entry_id:     entry.id,
          plate:        entry.index || null
        });
      }
    }
  }
  return { techniques, atoms };
}

/* --- serialise as a Shell.registerCrossover(name, data) call ------------- */
function emit(name, data, note) {
  const banner =
    '/* ' + name + '.js — GENERATED by scripts/build-crossover.mjs · ck-e13.\n' +
    '   Do not edit by hand; regenerate with `node scripts/build-crossover.mjs`.\n' +
    '   ' + note + '\n */\n';
  const body = 'Shell.registerCrossover(' + JSON.stringify(name) + ', ' +
               JSON.stringify(data, null, 2) + ');\n';
  return banner + body;
}

/* --- main -------------------------------------------------------------- */
const entries = loadManifest();
const { techniques, atoms } = build(entries);

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'techniques.js'),
  emit('techniques', techniques,
    `Fine-grained technique index: every entry that names a technique id in ` +
    `its spec.techniques[] appears here. Distinct from the coarse instance_of[] ` +
    `and uses[] aggregations the shell already computes from the manifest.`));

writeFileSync(join(OUT, 'atoms.js'),
  emit('atoms', atoms,
    `Fine-grained atom index: every technique block that names an atom in ` +
    `its atoms[] appears here. Distinct from the top-level entry.uses[] chain.`));

const techCount = Object.keys(techniques).length;
const atomCount = Object.keys(atoms).length;
const totalTechAppearances = Object.values(techniques).reduce((n, t) => n + t.appears_in.length, 0);
const totalAtomAppearances = Object.values(atoms).reduce((n, a) => n + a.used_by.length, 0);
console.log(`✔ crossover built`);
console.log(`  techniques.js — ${techCount} techniques, ${totalTechAppearances} appearances`);
console.log(`  atoms.js      — ${atomCount} atoms, ${totalAtomAppearances} uses`);
